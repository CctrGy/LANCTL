"""Generate the official v2 catalogs and the synchronous frontend English fallback."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from lanctl.shared.i18n import (  # noqa: E402
    ENGLISH_STRINGS,
    LanguageManager,
    _english_document,
    spanish_document,
)


def outputs():
    return {
        ROOT / "bundled/languages/english.lang": json.dumps(
            _english_document(), ensure_ascii=False, indent=2
        )
        + "\n",
        ROOT / "bundled/languages/spanish.lang": json.dumps(
            spanish_document(), ensure_ascii=False, indent=2
        )
        + "\n",
        ROOT
        / "gui/i18n-defaults.js": '"use strict";\n// Generated by tools/generate_language_catalogs.py.\nwindow.LANCTL_DEFAULT_STRINGS = Object.freeze('
        + json.dumps(ENGLISH_STRINGS, ensure_ascii=False, indent=2)
        + ");\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Stale language resource: {path.relative_to(ROOT)}")
        else:
            path.write_text(text, encoding="utf-8")
    manager = LanguageManager(ROOT / "bundled/languages")
    catalogs = [
        manager.load_file(ROOT / f"bundled/languages/{name}.lang")
        for name in ("english", "spanish")
    ]
    if catalogs[0].strings.keys() != catalogs[1].strings.keys():
        raise SystemExit("English/Spanish key mismatch")
    print(f"Language catalogs: {len(catalogs[0].strings)} keys in each language")


if __name__ == "__main__":
    main()
