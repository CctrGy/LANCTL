"""Generate offline manifest and Inno choices from official .lang JSON sources."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from lanctl.shared.i18n import LanguageManager  # noqa: E402


def generate(root):
    root = Path(root)
    validator = LanguageManager(root)
    entries = []
    codes = set()
    for source in sorted(root.glob("*.lang")):
        if source.is_symlink():
            raise ValueError("Bundled languages must not be symlinks")
        catalog = validator.load_file(source)
        if catalog.code in codes:
            raise ValueError("Duplicate bundled language code")
        codes.add(catalog.code)
        if any(char in catalog.native_name for char in "\r\n\0"):
            raise ValueError("Invalid language display name")
        entries.append(
            {
                "code": catalog.code,
                "nativeName": catalog.native_name,
                "file": source.name,
                "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            }
        )
    if "en" not in codes:
        raise ValueError("English must be bundled")
    entries.sort(key=lambda item: (item["code"] != "en", item["code"]))
    manifest = (
        json.dumps({"schemaVersion": 1, "languages": entries}, ensure_ascii=False, indent=2) + "\n"
    )
    lines = [
        "; Generated by tools/generate_installer_languages.py; do not edit.",
        "procedure AddProgramLanguages;",
        "begin",
    ]
    for entry in entries:
        code, label = entry["code"].replace("'", "''"), entry["nativeName"].replace("'", "''")
        lines.extend(
            [
                f"  ProgramLanguageCodes.Add('{code}');",
                f"  ProgramLanguageCombo.Items.Add('{label}');",
            ]
        )
    lines.extend(["end;", ""])
    return manifest, "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = zip(
        (ROOT / "bundled/languages/catalog.json", ROOT / "packaging/inno/program-languages.iss"),
        generate(ROOT / "bundled/languages"),
    )
    for path, text in outputs:
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Stale installer language resource: {path}")
        else:
            path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
